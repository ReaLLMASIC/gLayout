def J(name):
    return json.load(open(paths.RESULTS / name))


def pct(x, nd=1):
    return f"{100 * x:.{nd}f}"


def r2(x):
    """Two decimals, rounding half up on the decimal value."""
    from decimal import Decimal, ROUND_HALF_UP
    return str(Decimal(repr(round(x, 6))).quantize(Decimal("0.01"), rounding=ROUND_HALF_UP))


def signed(x, nd=1):
    return ("+" if x > 0 else "") + pct(x, nd)


