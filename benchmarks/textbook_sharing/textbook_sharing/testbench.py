def make_testbench(circuit, dut_name, include_path, case, pdk):
    return GEN[CATEGORY[circuit.circuit_id]](circuit, dut_name, include_path, case, pdk)


def derived(meas: dict) -> dict:
    """Derived metrics: phase margin from ph_lf/ph_ugf (inverting path has 180 deg at DC)."""
    out = dict(meas)
    if "vout_test" in meas and "rout_t" in meas:
        out["rout_nom"] = meas["rout_t"]
    if "ph_ugf" in meas and "ph_lf" in meas:
        out["pm"] = 180.0 - abs(meas["ph_lf"] - meas["ph_ugf"])
    if "dev_at_vdd" in meas:
        out["ok_at_vdd"] = 1.0 if meas["dev_at_vdd"] <= 0.05 else 0.0
    return out


def check_specs(meas: dict, specs: dict) -> dict:
    details = {}; ok = True
    for m, sp in specs.items():
        if m.startswith("_") or not isinstance(sp, dict): continue
        v = meas.get(m.lower())
        d = {"value": v, "spec": sp}
        if v is None or (isinstance(v, float) and (math.isnan(v) or math.isinf(v))):
            d["ok"] = False; d["why"] = "missing or NaN"
        else:
            good = True
            if sp.get("min") is not None and v < sp["min"]: good = False
            if sp.get("max") is not None and v > sp["max"]: good = False
            if sp.get("abs_max") is not None and abs(v) > sp["abs_max"]: good = False
            d["ok"] = good
        ok = ok and d["ok"]; details[m] = d
    return {"ok": ok, "details": details, "status": "passed" if ok else "spec_failed"}
